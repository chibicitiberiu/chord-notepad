#!/usr/bin/env python3
"""Converts the Material Design Icons the app uses into Android vector drawables.

The icons come from the Pictogrammers ``@mdi/svg`` npm package (Apache-2.0
icons; see its LICENSE), pinned by version and sha256. The tarball is
downloaded once into ``$CHORD_NOTEPAD_ANDROID_CACHE/mdi`` and checked against
the pin on every run. Each SVG is a single 24x24 path, so the conversion is a
straight copy of the path data into ``res/drawable/mdi_<name>.xml`` (black
fill; Compose tints it). The output is committed; ``--check`` verifies it.

The app's own icons (capo, 3/4 time signature, the Transpose composite and
the Convert arrow) are hand-written drawables next to these and are not
touched here.

Usage:
    python3 android/tools/mdi_icons.py [--check]
"""
import argparse
import hashlib
import os
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

VERSION = "7.4.47"
URL = f"https://registry.npmjs.org/@mdi/svg/-/svg-{VERSION}.tgz"
SHA256 = "de92e5dc9ce46c392ab5c53aa7190b19f82b40cb48872a083f788c7e13e91fef"

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "android/app/src/main/res/drawable"

# The names docs/design/android-ui-spec.md lists, plus the instrument sheet's
# family markers (circle, circle-outline).
ICONS = [
    "plus", "undo", "redo", "swap-vertical", "music-note", "piano", "metronome",
    "music-clef-treble", "music", "guitar-acoustic", "speedometer", "skip-previous",
    "play", "pause", "dock-bottom", "label", "repeat", "pencil", "play-circle",
    "content-save", "menu", "file-plus", "folder-open", "file-music",
    "content-save-edit", "export", "cog", "book-open-variant", "school",
    "information", "magnify-plus", "magnify-minus", "arrow-left", "chevron-right",
    "chevron-down", "radiobox-marked", "radiobox-blank", "circle", "circle-outline",
]

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Design Icons {version}, "{name}" (Pictogrammers, Apache-2.0).
     Generated by android/tools/mdi_icons.py; don't edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FF000000"
        android:pathData="{path}" />
</vector>
"""


def tarball() -> Path:
    cache = os.environ.get("CHORD_NOTEPAD_ANDROID_CACHE")
    if not cache:
        raise SystemExit("CHORD_NOTEPAD_ANDROID_CACHE is not set (source android/local.env)")
    path = Path(cache) / "mdi" / f"svg-{VERSION}.tgz"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".part")
        with urllib.request.urlopen(URL) as r, open(tmp, "wb") as f:
            f.write(r.read())
        tmp.rename(path)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"{path}: sha256 {digest}, expected {SHA256}")
    return path


def path_of(svg: str, name: str) -> str:
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1 or 'viewBox="0 0 24 24"' not in svg:
        raise SystemExit(f"{name}: expected one path on a 24x24 grid")
    return paths[0]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="compare, don't write")
    args = ap.parse_args()
    bad = 0
    with tarfile.open(tarball()) as tar:
        for name in ICONS:
            member = tar.extractfile(f"package/svg/{name}.svg")
            if member is None:
                raise SystemExit(f"{name}: not in the package")
            xml = TEMPLATE.format(version=VERSION, name=name, path=path_of(member.read().decode(), name))
            target = OUT / f"mdi_{name.replace('-', '_')}.xml"
            if args.check:
                if not target.exists() or target.read_text(encoding="utf-8") != xml:
                    print(f"differs: {target.name}")
                    bad += 1
            else:
                target.write_text(xml, encoding="utf-8")
    known = {f"mdi_{n.replace('-', '_')}.xml" for n in ICONS}
    for extra in sorted(p.name for p in OUT.glob("mdi_*.xml") if p.name not in known):
        print(f"not in the list: {extra}")
        bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
