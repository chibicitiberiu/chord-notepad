#!/usr/bin/env python3
"""Generate the character tables the iOS kit's find bar matches with.

The find bar finds in Swift (as you type, on the main actor), but the
session's ``replace_match`` checks the span again with the core's
``text_ops.find_all``, which is Python's ``re``: a literal pattern,
``re.IGNORECASE`` unless match case, ``(?<!\\w)`` and ``(?!\\w)`` around it
for whole words. A span Python doesn't call a match is silently not
replaced, so the Swift side must agree with ``re`` character for
character. This writes what ``re`` decides with, from this Python's own
character database, into
``ios/ChordNotepadKit/Sources/ChordNotepadKit/Generated/PythonText.swift``:

- ``_sre.unicode_tolower`` (the simple lowercase ``re`` folds with), as
  pairs where it changes the character;
- ``_sre.unicode_iscased`` (an uncased pattern character only matches
  itself), as ranges;
- ``\\w`` (``str.isalnum()`` or ``_``), as ranges;
- ``re._casefix._EXTRA_CASES``: characters with the same uppercase but
  another lowercase (``s`` and ``ſ``, ``σ`` and ``ς``), which ``re`` also
  lets match.

Tables rather than Swift's own Unicode properties: on iOS those come from
the OS's Swift runtime, whose Unicode version is the device's, and their
case mappings are the full ones (``İ`` lowercases to two characters).

Run it with the Python the app ships (3.14, Unicode 16.0)::

    python3 -I ios/tools/gen_find_tables.py           # write the file
    python3 -I ios/tools/gen_find_tables.py --check   # exit 1 if it is stale
"""

import argparse
import _sre
import re._casefix
import sys
import unicodedata
from pathlib import Path
from typing import Callable, List, Tuple

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / "ios" / "ChordNotepadKit" / "Sources" / "ChordNotepadKit" / "Generated" / "PythonText.swift"
MAX = 0x10FFFF


def _ranges(test: Callable[[int], bool]) -> List[Tuple[int, int]]:
    out: List[Tuple[int, int]] = []
    start = None
    for cp in range(MAX + 2):
        inside = cp <= MAX and not 0xD800 <= cp <= 0xDFFF and test(cp)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def _numbers(values: List[int], per_line: int = 8) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"0x{v:X}" for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def generate() -> str:
    lower = [(cp, _sre.unicode_tolower(cp)) for cp in range(MAX + 1)
             if not 0xD800 <= cp <= 0xDFFF and _sre.unicode_tolower(cp) != cp]
    cased = _ranges(_sre.unicode_iscased)
    word = _ranges(lambda cp: chr(cp).isalnum() or cp == 0x5F)
    extra = sorted(re._casefix._EXTRA_CASES.items())
    flat_lower = [v for pair in lower for v in pair]
    flat_cased = [v for pair in cased for v in pair]
    flat_word = [v for pair in word for v in pair]
    extra_lines = "\n".join(f"    0x{k:X}: [{', '.join(f'0x{v:X}' for v in vs)}]," for k, vs in extra)
    version = f"{sys.version_info.major}.{sys.version_info.minor}"
    return f"""// Generated by ios/tools/gen_find_tables.py from Python {version}'s `re`
// (Unicode {unicodedata.unidata_version}). Do not edit; regenerate with the Python the app ships.

/// The Unicode version the tables are from.
let pythonTextUnicodeVersion = "{unicodedata.unidata_version}"

/// `_sre.unicode_tolower` where it changes a character: code point, lowercase, ... (sorted).
let pythonLowerPairs: [UInt32] = [
{_numbers(flat_lower)}
]

/// `_sre.unicode_iscased`: first, last, ... (inclusive, sorted).
let pythonCasedRanges: [UInt32] = [
{_numbers(flat_cased)}
]

/// `\\w` in a str pattern (`str.isalnum()` or `_`): first, last, ... (inclusive, sorted).
let pythonWordRanges: [UInt32] = [
{_numbers(flat_word)}
]

/// `re._casefix._EXTRA_CASES`: a lowercase character and the others that match it ignoring case.
let pythonExtraCases: [UInt32: [UInt32]] = [
{extra_lines}
]
"""


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args(argv)
    text = generate()
    current = OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == text
    if args.check:
        if not current:
            print(f"stale: {OUTPUT.relative_to(REPO)} (run python3 -I ios/tools/gen_find_tables.py)",
                  file=sys.stderr)
        return 0 if current else 1
    if not current:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
