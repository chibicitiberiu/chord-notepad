#!/usr/bin/env python3
"""Generate ChordNotepadKit's Swift bridge types from android/bridge_schema.json.

The schema is the bridge contract dumped from the core's dataclasses
(``python -m chordnotepad.session.bridge --schema``; docs/ANDROID.md, "Schema
and contract test"). From it this writes:

- ``Sources/ChordNotepadKit/Generated/Bridge.swift``: a Codable struct per DTO
  (states, events, requests and the values nested in them), a String enum per
  enum, ``SessionOutput`` (every output decoded by its wire type name) and a
  typed ``BridgeCommand`` builder per command, plus ``respond`` helpers per
  request type.
- ``Tests/ChordNotepadKitTests/Generated/CommandSamples.swift``: two calls of
  every builder (nullable arguments null, then set), which the kit tests send
  through the core's own ``session.bridge.decode_args``.

Rules the output follows (docs/IOS.md, "Bridge contract"):

- Swift names are the wire names in lowerCamelCase, mapped back by explicit
  ``CodingKeys``; no key-decoding strategy is involved. A name that is a Swift
  keyword is backticked (``TimelineSection.repeat``).
- Every struct encodes every key, a nil optional as ``null``:
  ``decode_args`` rejects a missing key (``session/bridge.py``), and a
  ``DocumentRef`` or ``SettingsValues`` must carry exactly its fields.
  Decoding is synthesized: unknown keys are ignored (a newer core), a missing
  non-optional field is an error.
- Builders take every parameter and always write every key, so no default can
  drift between Swift and Python (the schema doesn't record defaults).
- ``json`` and ``any`` are ``JSONValue``; ``selection`` is ``Selection?``
  (``[start, end]`` or null); tuples and lists are arrays.

Usage (from the repo root)::

    python3 -I ios/tools/gen_swift_bridge.py           # write both files
    python3 -I ios/tools/gen_swift_bridge.py --check   # exit 1 if either is stale
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

REPO = Path(__file__).resolve().parents[2]
SCHEMA = REPO / "android" / "bridge_schema.json"
KIT = REPO / "ios" / "ChordNotepadKit"
BRIDGE_SWIFT = KIT / "Sources" / "ChordNotepadKit" / "Generated" / "Bridge.swift"
SAMPLES_SWIFT = KIT / "Tests" / "ChordNotepadKitTests" / "Generated" / "CommandSamples.swift"

HEADER = """\
// GENERATED by ios/tools/gen_swift_bridge.py from android/bridge_schema.json.
// Do not edit: change the core's DTOs, regenerate the schema, then run
// `make ios-bridge-gen`. tests/test_ios_swift_bridge.py fails while it is stale.
"""

# Every Swift keyword (declarations, statements, expressions, types and the
# contextual ones that can't be a plain identifier everywhere).
SWIFT_KEYWORDS = frozenset("""
    associatedtype borrowing class consuming deinit enum extension fileprivate func import
    init inout internal let nonisolated open operator package precedencegroup private
    protocol public rethrows static struct subscript typealias var
    break case catch continue default defer do else fallthrough for guard if in repeat
    return switch throw where while
    Any as await false is nil self Self super throws true try
    _ associativity convenience didSet dynamic final get indirect infix lazy left mutating
    none nonmutating optional override postfix prefix required right set some Type
    unowned weak willSet
""".split())

# Members that stay awkward even backticked: ``.none`` reads as Optional.none,
# the others are the language's own members.
AWKWARD_MEMBERS = frozenset({"none", "self", "Self", "Type", "Protocol", "init"})

# Enum cases renamed in Swift (the raw value stays the wire value).
CASE_NAMES: Dict[Tuple[str, str], str] = {
    ("StartupScreen", "none"): "noScreen",
}

KIND_ORDER = ("state", "event", "request", "value")


def camel(name: str) -> str:
    """``text_revision`` → ``textRevision``."""
    head, *rest = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def upper_camel(name: str) -> str:
    """``text_revision`` → ``TextRevision``."""
    lower = camel(name)
    return lower[:1].upper() + lower[1:]


def ident(name: str) -> str:
    """A Swift identifier for a wire name, backticked if it is a keyword."""
    swift = camel(name)
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", swift):
        raise ValueError(f"{name!r} isn't a valid Swift identifier")
    return f"`{swift}`" if swift in SWIFT_KEYWORDS else swift


def bare(identifier: str) -> str:
    """An identifier without its backticks (for labels in strings)."""
    return identifier.strip("`")


def case_name(enum: str, value: str) -> str:
    """The Swift case for one enum value."""
    if (enum, value) in CASE_NAMES:
        return CASE_NAMES[(enum, value)]
    swift = camel(value)
    if swift in AWKWARD_MEMBERS:
        raise ValueError(f"{enum}.{value}: add a CASE_NAMES entry ({swift!r} is awkward as a case)")
    return f"`{swift}`" if swift in SWIFT_KEYWORDS else swift


class Types:
    """Maps schema type strings to Swift types and sample values."""

    def __init__(self, schema: dict) -> None:
        self.dtos: Dict[str, dict] = schema["types"]
        self.enums: Dict[str, List[str]] = schema["enums"]

    def swift(self, type_name: str) -> str:
        """The Swift type for a schema field or parameter type."""
        if type_name.endswith("|null"):
            inner = type_name[: -len("|null")]
            return self.swift(inner) + "?"
        if type_name.startswith("list[") and type_name.endswith("]"):
            return "[" + self.swift(type_name[5:-1]) + "]"
        simple = {"str": "String", "int": "Int", "float": "Double", "bool": "Bool",
                  "json": "JSONValue", "any": "JSONValue", "selection": "Selection?"}
        if type_name in simple:
            return simple[type_name]
        if type_name.startswith("dict[str,str]"):
            return "[String: String]"
        if type_name in self.dtos or type_name in self.enums:
            return type_name
        raise ValueError(f"unknown schema type {type_name!r}")

    def sample(self, type_name: str, full: bool, depth: int = 0) -> str:
        """A Swift expression of the type: nil for nullables unless ``full``."""
        if type_name.endswith("|null"):
            if not full:
                return "nil"
            return self.sample(type_name[: -len("|null")], full, depth)
        if type_name == "selection":
            return "Selection(start: 0, end: 1)" if full else "nil"
        if type_name.startswith("list["):
            if full and depth < 2:
                return "[" + self.sample(type_name[5:-1], full, depth + 1) + "]"
            return "[]"
        if type_name.startswith("dict[str,str]"):
            return '["field": "value"]' if full else "[:]"
        simple = {"str": '"text"', "int": "1", "float": "1.5", "bool": "true"}
        if type_name in simple:
            return simple[type_name]
        if type_name in ("json", "any"):
            return '.object(["key": .string("value")])' if full else ".null"
        if type_name in self.enums:
            return "." + bare(case_name(type_name, self.enums[type_name][0]))
        if type_name in self.dtos:
            fields = self.dtos[type_name]["fields"]
            args = ", ".join(f"{bare(ident(f))}: {self.sample(t, full, depth + 1)}"
                             for f, t in fields.items())
            return f"{type_name}({args})"
        raise ValueError(f"unknown schema type {type_name!r}")


def gen_enum(name: str, values: List[str]) -> List[str]:
    out = [f"public enum {name}: String, Codable, Sendable, CaseIterable {{"]
    for value in values:
        swift = case_name(name, value)
        out.append(f"    case {swift}" + ("" if bare(swift) == value else f" = {json.dumps(value)}"))
    out.append("}")
    return out


def gen_struct(name: str, spec: dict, types: Types) -> List[str]:
    fields: Dict[str, str] = spec["fields"]
    out = [f"/// `{name}` ({spec['kind']})."]
    out.append(f"public struct {name}: Codable, Sendable, Equatable {{")
    for field, type_name in fields.items():
        out.append(f"    public var {ident(field)}: {types.swift(type_name)}")
    if not fields:
        out.append("    public init() {}")
        out.append("}")
        return out
    out.append("")
    params = ", ".join(f"{bare(ident(f))}: {types.swift(t)}" for f, t in fields.items())
    out.append(f"    public init({params}) {{")
    for field in fields:
        out.append(f"        self.{ident(field)} = {ident(field)}")
    out.append("    }")
    out.append("")
    out.append("    enum CodingKeys: String, CodingKey {")
    for field in fields:
        swift = ident(field)
        out.append(f"        case {swift}" + ("" if bare(swift) == field else f" = {json.dumps(field)}"))
    out.append("    }")
    out.append("")
    out.append("    /// Every key, nil as null (the core's decoders want them all).")
    out.append("    public func encode(to encoder: Encoder) throws {")
    out.append("        var container = encoder.container(keyedBy: CodingKeys.self)")
    for field in fields:
        out.append(f"        try container.encode({ident(field)}, forKey: .{ident(field)})")
    out.append("    }")
    out.append("}")
    return out


def gen_outputs(types: Types) -> List[str]:
    outputs = [(n, s) for n, s in types.dtos.items() if s["kind"] in ("state", "event", "request")]
    outputs.sort(key=lambda item: (KIND_ORDER.index(item[1]["kind"]), item[0]))
    out = [
        "/// What kind of output a wire type is.",
        "public enum OutputKind: String, Sendable {",
        "    case state, event, request",
        "}",
        "",
        "/// A session output decoded by its wire type name (`onEvent(type_name, json)`).",
        "public enum SessionOutput: Sendable, Equatable {",
    ]
    for name, _ in outputs:
        out.append(f"    case {ident(lower_first(name))}({name})")
    out += [
        "",
        "    /// The wire type name (the Python class name).",
        "    public var typeName: String {",
        "        switch self {",
    ]
    for name, _ in outputs:
        out.append(f'        case .{bare(ident(lower_first(name)))}: return "{name}"')
    out += ["        }", "    }", "", "    public var kind: OutputKind {", "        switch self {"]
    for name, spec in outputs:
        out.append(f"        case .{bare(ident(lower_first(name)))}: return .{spec['kind']}")
    out += [
        "        }",
        "    }",
        "",
        "    /// Decode one output.",
        "    ///",
        "    /// - Throws: ``BridgeDecodeError`` for an unknown type name or a payload",
        "    ///   that doesn't match the type (unknown keys are ignored).",
        "    public static func decode(typeName: String, json: String) throws -> SessionOutput {",
        "        let data = Data(json.utf8)",
        "        do {",
        "            switch typeName {",
    ]
    for name, _ in outputs:
        out.append(f'            case "{name}": return .{bare(ident(lower_first(name)))}'
                   f"(try BridgeJSON.decoder.decode({name}.self, from: data))")
    out += [
        "            default: throw BridgeDecodeError.unknownType(typeName)",
        "            }",
        "        } catch let error as BridgeDecodeError {",
        "            throw error",
        "        } catch {",
        "            throw BridgeDecodeError.badPayload(typeName, String(describing: error))",
        "        }",
        "    }",
        "}",
    ]
    return out


def lower_first(name: str) -> str:
    return name[:1].lower() + name[1:]


def gen_schema_facts(schema: dict, types: Types) -> List[str]:
    out = [
        "/// Facts about the schema the code was generated from (for contract tests).",
        "public enum BridgeSchema {",
        f"    public static let version = {schema['version']}",
        "",
        "    /// Every command name the core accepts.",
        "    public static let commandNames: [String] = [",
    ]
    out += [f'        "{c}",' for c in schema["commands"]]
    out += ["    ]", "", "    /// Each DTO's wire field names, by type name.",
            "    public static let fieldNames: [String: [String]] = ["]
    for name, spec in types.dtos.items():
        fields = ", ".join(json.dumps(f) for f in spec["fields"])
        out.append(f'        "{name}": [{fields}],')
    out += ["    ]", "", "    /// Each enum's wire values, by enum name.",
            "    public static let enumValues: [String: [String]] = ["]
    for name, values in types.enums.items():
        out.append(f'        "{name}": [{", ".join(json.dumps(v) for v in values)}],')
    out += ["    ]", "}"]
    return out


def gen_commands(schema: dict, types: Types) -> List[str]:
    params_by_command: Dict[str, Dict[str, str]] = schema["command_params"]
    out = ["extension BridgeCommand {"]
    for command in schema["commands"]:
        params = params_by_command[command]
        func = ident(command)
        out.append("")
        out.append(f"    /// `{command} {{" + ", ".join(params) + "}`.")
        signature = ", ".join(f"{bare(ident(p))}: {types.swift(t)}" for p, t in params.items())
        out.append(f"    public static func {func}({signature}) -> BridgeCommand {{")
        if not params:
            out.append(f'        BridgeCommand(name: "{command}", args: EmptyArgs())')
            out.append("    }")
            continue
        args_type = upper_camel(command) + "Args"
        out.append(f"        struct {args_type}: Encodable, Sendable {{")
        for p, t in params.items():
            out.append(f"            let {ident(p)}: {types.swift(t)}")
        out.append("            enum CodingKeys: String, CodingKey {")
        for p in params:
            swift = ident(p)
            out.append(f"                case {swift}" + ("" if bare(swift) == p else f" = {json.dumps(p)}"))
        out.append("            }")
        out.append("            func encode(to encoder: Encoder) throws {")
        out.append("                var container = encoder.container(keyedBy: CodingKeys.self)")
        for p in params:
            out.append(f"                try container.encode({ident(p)}, forKey: .{ident(p)})")
        out.append("            }")
        out.append("        }")
        args = ", ".join(f"{bare(ident(p))}: {ident(p)}" for p in params)
        out.append(f'        return BridgeCommand(name: "{command}", args: {args_type}({args}))')
        out.append("    }")
    out += gen_answers(schema, types)
    out.append("}")
    return out


def gen_answers(schema: dict, types: Types) -> List[str]:
    """``respond`` with a typed value per request type (``answers``)."""
    out: List[str] = []
    for request, answer in sorted(schema["answers"].items()):
        value_type = types.swift(answer)
        func = "respondTo" + request
        out.append("")
        out.append(f"    /// `respond` to a `{request}`: `{answer}` (nil cancels).")
        out.append(f"    public static func {func}(requestId: Int, value: {value_type}) -> BridgeCommand {{")
        out.append('        BridgeCommand(name: "respond", args: RespondArgs(requestId: requestId, value: value))')
        out.append("    }")
    return out


def gen_bridge(schema: dict) -> str:
    types = Types(schema)
    lines = [HEADER, "import Foundation", ""]
    lines.append("// MARK: - Enums")
    for name, values in schema["enums"].items():
        lines.append("")
        lines += gen_enum(name, values)
    dtos = sorted(types.dtos.items(), key=lambda item: (KIND_ORDER.index(item[1]["kind"]), item[0]))
    for kind in KIND_ORDER:
        lines.append("")
        lines.append(f"// MARK: - {kind.capitalize()} types")
        for name, spec in dtos:
            if spec["kind"] == kind:
                lines.append("")
                lines += gen_struct(name, spec, types)
    lines.append("")
    lines.append("// MARK: - Outputs")
    lines.append("")
    lines += gen_outputs(types)
    lines.append("")
    lines.append("// MARK: - Commands")
    lines.append("")
    lines += gen_commands(schema, types)
    lines.append("")
    lines += gen_schema_facts(schema, types)
    return "\n".join(lines) + "\n"


def gen_samples(schema: dict) -> str:
    types = Types(schema)
    lines = [HEADER, "@testable import ChordNotepadKit", ""]
    lines.append("/// Every builder: with nullable arguments nil and empty lists, then (when")
    lines.append("/// that differs) with every one set.")
    lines.append("let commandSamples: [BridgeCommand] = [")
    for command in schema["commands"]:
        params = schema["command_params"][command]
        calls = []
        for full in (False, True):
            args = ", ".join(f"{bare(ident(p))}: {types.sample(t, full)}" for p, t in params.items())
            call = f"    .{bare(ident(command))}({args}),"
            if call not in calls:
                calls.append(call)
        lines += calls
    lines.append("]")
    lines.append("")
    lines.append("/// Every respond helper, with a value and with nil, by the request type it answers.")
    lines.append("let respondSamples: [(requestType: String, command: BridgeCommand)] = [")
    for request, answer in sorted(schema["answers"].items()):
        for full in (True, False):
            sample = types.sample(answer, full)
            lines.append(f'    ("{request}", .respondTo{request}(requestId: 7, value: {sample})),')
    lines.append("]")
    return "\n".join(lines) + "\n"


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a generated file is stale")
    args = parser.parse_args(argv)
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    outputs = {BRIDGE_SWIFT: gen_bridge(schema), SAMPLES_SWIFT: gen_samples(schema)}
    stale = [path for path, text in outputs.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(REPO)} (run make ios-bridge-gen)", file=sys.stderr)
        return 1 if stale else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
